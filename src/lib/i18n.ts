const dictionary = { 'zh-CN': zh, en } as const
export type TranslationKey = keyof typeof zh
export const t = (locale: Locale, key: TranslationKey, variables?: Record<string, string | number>) => {
  let value: string = dictionary[locale][key]
  for (const [name, replacement] of Object.entries(variables ?? {})) value = value.replace(`{${name}}`, String(replacement))
  return value
}

/** The stored value that means "follow the system language", mirroring the
 * upstream AppLanguageSetting.systemDefault sentinel. */
export const SYSTEM_LOCALE = 'system' as const
export type LocaleSetting = Locale | typeof SYSTEM_LOCALE

/**
 * Resolves a stored language setting to a supported UI locale. "system" (or an
 * unknown value) follows navigator.languages, taking the first entry whose
 * primary subtag matches a bundled language; zh-CN is the fallback default.
 */
export const resolveLocale = (setting: string | undefined, systemLanguages: readonly string[] = navigatorLanguages()): Locale => {
  if (setting && setting !== SYSTEM_LOCALE && (setting === 'zh-CN' || setting === 'en')) return setting
  for (const language of systemLanguages) {
    const primary = language.toLowerCase().split('-')[0]
    if (primary === 'zh') return 'zh-CN'
    if (primary === 'en') return 'en'
  }
  return 'zh-CN'
}

const navigatorLanguages = (): readonly string[] =>
  typeof navigator !== 'undefined' && Array.isArray(navigator.languages) ? navigator.languages : []
